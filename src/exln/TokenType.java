package exln;

public enum TokenType {
    // SINGLE CHARACTER TOKENS
    LEFT_PAREN, RIGHT_PAREN, LEFT_BRACE, RIGHT_BRACE,
    LEFT_BRACKET, RIGHT_BRACKET,
    COMMA, DOT, SEMICOLON,
    PLUS,  MINUS, STAR, COLON,

    // ONE OR TWO-CHARACTER TOKENS
    BANG, BANG_EQUAL,
    EQUAL, EQUAL_EQUAL,
    GREATER, GREATER_EQUAL,
    LESS, LESS_EQUAL, SLASH,

    // LITERALS
    IDENTIFIER, STRING, NUMBER,

    // RESERVED WORDS
    AND, ENUM, RETURN, BREAK, FALSE, SUPER,
    CASE, FOR, SWITCH, CLASS, FUNC, THIS,
    CONTINUE, IF, TRUE, DEFAULT, NULL, VAR,
    DO, OR, WHILE, ELSE, PRINT,

    //END OF FILE
    EOF
}
